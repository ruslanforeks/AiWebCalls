"""Прайс закупки пшеницы по протеину.

Вынесен из промпта в данные сознательно. Цена — единственное, что агент
говорит от лица компании, и фермер вправе на неё сослаться. Цифра в тексте
промпта не проверяется ничем: модель может её переставить, округлить или
придумать промежуточное значение. Здесь она проверена тестами, а модель
получает уже готовый ответ.

Прайс меняется, поэтому лежит отдельным файлом и правится без правок кода.
"""

from __future__ import annotations

from dataclasses import dataclass

#: Ступени прайса: протеин в процентах → цена за тонну в рублях.
#: Отсортированы по убыванию — поиск идёт сверху вниз.
PRICE_TIERS: tuple[tuple[float, int], ...] = (
    (14.0, 13000),
    (13.5, 12800),
    (13.0, 12600),
    (12.5, 12400),
    (12.0, 12200),
)

#: Ниже этого протеина прайса нет: такое зерно оценивает руководитель.
MIN_PROTEIN = PRICE_TIERS[-1][0]

#: НДС на зерно в России — 10%, а не общие 20%.
#: Ставки в PRICE_TIERS указаны БЕЗ НДС.
VAT_RATE = 0.10


@dataclass(frozen=True)
class Quote:
    """Цена, которую агент может назвать."""

    protein: float
    price: int
    #: Ступень прайса, по которой посчитано. Отличается от protein, когда
    #: фермер назвал промежуточное значение.
    tier: float

    @property
    def is_exact(self) -> bool:
        """Совпал ли протеин со ступенью прайса точно."""
        return self.protein == self.tier

    @property
    def price_with_vat(self) -> int:
        """Цена с НДС, для хозяйств, работающих с налогом.

        Округляется до целого рубля: копейки в разговоре не произносят.
        """
        return round(self.price * (1 + VAT_RATE))

    def for_vat(self, *, with_vat: bool) -> int:
        """Цена под систему налогообложения собеседника.

        Вопрос про НДС задаётся раньше цены не из вежливости: одна и та же
        партия стоит на десять процентов разное, и назвать цифру, не зная
        ответа, — значит назвать неверную.
        """
        return self.price_with_vat if with_vat else self.price


def quote_for_protein(protein: float | None) -> Quote | None:
    """Подобрать цену по протеину.

    Промежуточные значения округляются **вниз** до ближайшей ступени:
    протеин 13.2 оценивается как 13.0. Округление вверх означало бы, что
    компания платит за качество, которого в зерне нет, и разницу
    обнаружат уже на элеваторе.

    Протеин выше верхней ступени оценивается по ней же: сверх четырнадцати
    прайс не растёт, и надбавку решает руководитель.

    Args:
        protein: Протеин в процентах, как назвал фермер.

    Returns:
        Цена либо None, если протеин ниже прайса или не назван.
    """
    if protein is None or protein < MIN_PROTEIN:
        return None

    for tier, price in PRICE_TIERS:
        if protein >= tier:
            return Quote(protein=protein, price=price, tier=tier)

    return None


def format_price_table() -> str:
    """Прайс словами, как его произносят вслух.

    Модель читает эту таблицу в промпте, поэтому числа записаны так,
    чтобы она не пыталась произносить «13000» цифрами.
    """
    lines = []
    for tier, price in PRICE_TIERS:
        tier_text = f"{tier:g}".replace(".", ",")
        with_vat = round(price * (1 + VAT_RATE))
        lines.append(
            f"  протеин {tier_text} — {price} без НДС, {with_vat} с НДС"
        )
    return "\n".join(lines)


def _spell_price(price: int) -> str:
    """Записать цену так, как её произносят вслух.

    «Тринадцать тысяч», а не «тринадцать тысяч ноль рублей»: круглую сумму
    человек договаривает до рублей только в документах.
    """
    thousands, rest = divmod(price, 1000)
    if rest == 0:
        return f"{thousands} тысяч"
    return f"{thousands} тысяч {rest}"
